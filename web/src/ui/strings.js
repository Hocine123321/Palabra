export function pickLanguage(languages = []) {
  return [].concat(languages).some((l) => String(l).toLowerCase().startsWith("ar")) ? "ar" : "en";
}

export function makeT(lang) {
  return (key) => (lang === "ar" ? AR[key] ?? key : key);
}

/** Western digits stay Western: the app shows them that way too. Only direction and words change. */
export const dirFor = (lang) => (lang === "ar" ? "rtl" : "ltr");

/**
 * The text for any error the link can raise, in the page's language. Errors keep their English `message` (logs, tests);
 * this maps the stable `kind` (and the numbers some carry) to a translated sentence. Unknown errors show their own message.
 */
export function errorText(error, t, { englishMessage = (e) => e?.message ?? String(e) } = {}) {
  const english = englishMessage(error);
  const fill = (key, n) => t(key).replace("{n}", n);
  switch (error?.kind) {
    case "locked": return fill("Too many wrong codes. Try again in {n} seconds.", error.seconds);
    case "wrong": return fill("Wrong code. {n} tries left.", error.triesLeft);
    default: return t(english);   // every fixed message is its own key; anything else falls back to what it says
  }
}
